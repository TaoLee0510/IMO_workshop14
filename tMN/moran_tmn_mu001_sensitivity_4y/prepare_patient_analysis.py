"""Clone the approved patient figure pipeline and bind it to the new reference."""
from pathlib import Path
import json,shutil,hashlib
ROOT=Path(__file__).resolve().parent
def main():
    source=Path(json.loads((ROOT/'provenance.json').read_text())['previous_refit'])/'patient_analysis'
    target=ROOT/'patient_analysis';fitpath=ROOT/'results/fits/reference.json'
    fit=json.loads(fitpath.read_text());assert fit['status']=='fitted'
    if target.exists():raise SystemExit('Patient analysis exists; use its checkpoints rather than reinitialize.')
    for d in ['inputs','results','bin','figures/patients','qa','outputs/20261105_patient_analysis']:(target/d).mkdir(parents=True,exist_ok=True)
    for name in ['common.py','compute.py','plot_figures.py','validate_analysis.py','patient_simulator.cpp','requirements.txt']:
        shutil.copy2(source/name,target/name)
    shutil.copy2(ROOT/'model.py',target/'model.py')
    shutil.copy2(ROOT/'risk_backend.py',target/'risk_backend.py')
    shutil.copy2(ROOT/'memory_control.py',target/'memory_control.py')
    for old,new in [(fitpath,'fit.json'),(ROOT/'data/cohort.json','cohort.json'),(ROOT/'data/audit.json','cohort_audit.json'),(ROOT/'config.json','fit_config.json')]:
        shutil.copy2(old,target/'inputs'/new)
    manifest={'fit_source':str(fitpath),'fit_sha256':hashlib.sha256(fitpath.read_bytes()).hexdigest(),
      'cohort_sha256':hashlib.sha256((target/'inputs/cohort.json').read_bytes()).hexdigest(),
      'model_sha256':hashlib.sha256((target/'model.py').read_bytes()).hexdigest(),
      'replicates_per_patient':200,'horizon_days':1460,'master_seed':2026110521,'workers':1,'gamma_density_integral':1}
    (target/'analysis_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    code=(target/'compute.py').read_text()
    code=code.replace('from model import Backgrounds,ForwardFilter,tilt_for_horizon,cohort_loglik','from model import Backgrounds,ForwardFilter,tilt_for_horizon,cohort_loglik,suggested_cap')
    code='from risk_backend import RiskFilter\n'+code
    code=code.replace("f=ForwardFilter(P,A,THETA,bg.for_patient(0),killed=known,cap=FIT['cap'],eta=eta,refinement=1)",
       "cap=FIT['cap'] if known else suggested_cap(row,0,bg,A,THETA,P,end,FIT['cap'])\n    f=ForwardFilter(P,A,THETA,bg.for_patient(0),killed=known,cap=cap,eta=eta,refinement=1,window=not known)")
    code=code.replace("if known:f.logscale-=f.physical_logmass();f.state[-1]=0.","if known:f.condition_event_free()")
    code=code.replace("f.propagate(row['baseline_day'],0.);f.logscale-=f.physical_logmass();f.state[-1]=0.","f.propagate(row['baseline_day'],0.);f.condition_event_free()")
    code=code.replace('f=ForwardFilter(P,A,THETA,bg.for_patient(0),killed=True,cap=P.K-1,eta=eta,refinement=refinement)','f=RiskFilter(P,A,THETA,bg.for_patient(0),killed=True,cap=P.K-1,eta=eta,refinement=refinement)')
    code=code.replace('    f.propagate(0.,t);mass=f.physical_logmass(include_absorbed=True)','    f.risk_early_stop=True\n    f.propagate(0.,t);mass=f.physical_logmass(include_absorbed=True)')
    code=code.replace("type=int,default=3","type=int,default=1")
    code=code.replace('def pool_run(function,tasks,workers):\n', 'def pool_run(function,tasks,workers):\n    if workers==1:return [function(task) for task in tasks]\n')
    (target/'compute.py').write_text(code)
    common=(target/'common.py').read_text().replace("c=round(2*P.N*row['baseline_vaf'])","c=round(2*P.N*row['baseline_vaf'])-P.D_init")
    common=common.replace("'rounding_C_cells':c-2*P.N*row['baseline_vaf']","'rounding_C_cells':c+P.D_init-2*P.N*row['baseline_vaf']")
    common=common.replace('from model import Parameters','from model import Parameters\nimport memory_control')
    (target/'common.py').write_text(common)
    validation=(target/'validate_analysis.py').read_text().replace('pool_run(precision,COHORT,3)','pool_run(precision,COHORT,1)')
    (target/'validate_analysis.py').write_text(validation)
    plot=(target/'plot_figures.py').read_text()
    plot='import gc\n'+plot
    plot=plot.replace('plt.close(fig)','plt.close(fig);gc.collect()')
    (target/'plot_figures.py').write_text(plot)
    (target/'README.md').write_text('Patient-specific figures at the new mu=0.01 reference. Run compute.py stages simulate, vaf, risks and consolidate, then plot_figures.py --stage core and validate_analysis.py. Main report and workbook are generated by the parent sensitivity workflow. Each patient has 200 full Moran paths; the measured-baseline total founder burden is preserved. The frozen inference source supports high-mu state caps, moving active windows, separately accumulated absorbed mass and event-free day-0 conditioning.\\n')
    print(target)
if __name__=='__main__':main()
